<?php

declare(strict_types=1);

namespace Tests\Api\v1\MerchantPortal;

use App\Models\Merchant;
use App\Models\MerchantUser;
use App\Models\User;
use PHPUnit\Framework\Attributes\DataProvider;
use Symfony\Component\HttpFoundation\Response;
use Tests\Api\v1\Traits\MerchantPortalEndpoints;
use Tests\TestCase;

class CreateMerchantLocationTest extends TestCase
{
    use MerchantPortalEndpoints;

    private const array VALID_PAYLOAD = [
        'name' => 'Main Branch',
        'street' => 'No. 12, Jalan SS15/4a',
        'city' => 'Subang Jaya',
        'postcode' => '47500',
        'state' => 'Selangor',
    ];

    private const array VALID_LOCATION_RESPONSE_FIELDS = [
        'id',
        'merchantId',
        'name',
        'redemptionCode',
        'street',
        'city',
        'postcode',
        'state',
        'isActive',
        'createdAt',
        'updatedAt',
    ];

    private Merchant $merchant;

    private MerchantUser $owner;

    protected function setUp(): void
    {
        parent::setUp();

        $this->merchant = Merchant::factory()->create();
        $this->owner = MerchantUser::factory()->owner()->active()->for($this->merchant)->create();
    }

    public function testOwnerCanCreateLocation(): void
    {
        $response = $this->actingAs($this->owner, self::MERCHANT_USER_GUARD)
            ->postJson(self::createMerchantLocationEndpoint(), self::VALID_PAYLOAD);

        $response->assertStatus(Response::HTTP_CREATED)
            ->assertJson(['message' => 'Location created successfully.'])
            ->assertJsonStructure(['data' => self::VALID_LOCATION_RESPONSE_FIELDS])
            ->assertJsonFragment([
                'name' => 'Main Branch',
                'street' => 'No. 12, Jalan SS15/4a',
                'city' => 'Subang Jaya',
                'postcode' => '47500',
                'state' => 'Selangor',
                'merchantId' => $this->merchant->id,
            ]);

        $this->assertDatabaseHas('merchant_locations', [
            'merchant_id' => $this->merchant->id,
            'name' => 'Main Branch',
            'street' => 'No. 12, Jalan SS15/4a',
            'city' => 'Subang Jaya',
            'postcode' => '47500',
            'state' => 'Selangor',
        ]);
    }

    public function testRedemptionCodeIsAutoGenerated(): void
    {
        $response = $this->actingAs($this->owner, self::MERCHANT_USER_GUARD)
            ->postJson(self::createMerchantLocationEndpoint(), self::VALID_PAYLOAD);

        $response->assertStatus(Response::HTTP_CREATED);

        $redemptionCode = $response->json('data.redemptionCode');
        $this->assertNotNull($redemptionCode);

        $this->assertDatabaseHas('merchant_locations', [
            'merchant_id' => $this->merchant->id,
            'redemption_code' => $redemptionCode,
        ]);
    }

    public function testLocationIsInactiveByDefault(): void
    {
        $response = $this->actingAs($this->owner, self::MERCHANT_USER_GUARD)
            ->postJson(self::createMerchantLocationEndpoint(), self::VALID_PAYLOAD);

        $response->assertStatus(Response::HTTP_CREATED)
            ->assertJsonPath('data.isActive', false);
    }

    public function testRedemptionCodeIsUniquePerLocation(): void
    {
        $firstResponse = $this->actingAs($this->owner, self::MERCHANT_USER_GUARD)
            ->postJson(self::createMerchantLocationEndpoint(), self::VALID_PAYLOAD);

        $secondResponse = $this->actingAs($this->owner, self::MERCHANT_USER_GUARD)
            ->postJson(self::createMerchantLocationEndpoint(), self::VALID_PAYLOAD);

        $this->assertNotEquals(
            $firstResponse->json('data.redemptionCode'),
            $secondResponse->json('data.redemptionCode'),
        );
    }

    #[DataProvider('providesInvalidPayloads')]
    public function testOwnerCannotCreateLocationWithInvalidData(array $payload, array $expectedErrors): void
    {
        $response = $this->actingAs($this->owner, self::MERCHANT_USER_GUARD)
            ->postJson(self::createMerchantLocationEndpoint(), $payload);

        $response->assertStatus(Response::HTTP_UNPROCESSABLE_ENTITY)
            ->assertJsonValidationErrors($expectedErrors);
    }

    public static function providesInvalidPayloads(): array
    {
        return [
            'missing all fields' => [
                'payload' => [],
                'expectedErrors' => ['name', 'street', 'city', 'postcode', 'state'],
            ],
            'missing name' => [
                'payload' => array_diff_key(self::VALID_PAYLOAD, ['name' => null]),
                'expectedErrors' => ['name'],
            ],
            'missing street' => [
                'payload' => array_diff_key(self::VALID_PAYLOAD, ['street' => null]),
                'expectedErrors' => ['street'],
            ],
            'missing city' => [
                'payload' => array_diff_key(self::VALID_PAYLOAD, ['city' => null]),
                'expectedErrors' => ['city'],
            ],
            'missing postcode' => [
                'payload' => array_diff_key(self::VALID_PAYLOAD, ['postcode' => null]),
                'expectedErrors' => ['postcode'],
            ],
            'missing state' => [
                'payload' => array_diff_key(self::VALID_PAYLOAD, ['state' => null]),
                'expectedErrors' => ['state'],
            ],
            'name too long' => [
                'payload' => [...self::VALID_PAYLOAD, 'name' => str_repeat('a', 101)],
                'expectedErrors' => ['name'],
            ],
            'street too long' => [
                'payload' => [...self::VALID_PAYLOAD, 'street' => str_repeat('a', 256)],
                'expectedErrors' => ['street'],
            ],
            'city too long' => [
                'payload' => [...self::VALID_PAYLOAD, 'city' => str_repeat('a', 101)],
                'expectedErrors' => ['city'],
            ],
            'postcode not digits' => [
                'payload' => [...self::VALID_PAYLOAD, 'postcode' => 'ABCDE'],
                'expectedErrors' => ['postcode'],
            ],
            'postcode wrong length' => [
                'payload' => [...self::VALID_PAYLOAD, 'postcode' => '1234'],
                'expectedErrors' => ['postcode'],
            ],
            'invalid state' => [
                'payload' => [...self::VALID_PAYLOAD, 'state' => 'Atlantis'],
                'expectedErrors' => ['state'],
            ],
        ];
    }

    public function testStaffCannotCreateLocation(): void
    {
        $staff = MerchantUser::factory()->staff()->active()->for($this->merchant)->create();

        $response = $this->actingAs($staff, self::MERCHANT_USER_GUARD)
            ->postJson(self::createMerchantLocationEndpoint(), self::VALID_PAYLOAD);

        $response->assertStatus(Response::HTTP_FORBIDDEN)
            ->assertJson(['message' => 'Only the merchant owner can perform this action.']);
    }

    public function testCreateLocationRequiresAuthentication(): void
    {
        $response = $this->postJson(self::createMerchantLocationEndpoint(), self::VALID_PAYLOAD);

        $response->assertStatus(Response::HTTP_UNAUTHORIZED);
    }

    public function testCustomerCannotCreateLocation(): void
    {
        $customer = User::factory()->create();

        $response = $this->actingAs($customer, 'sanctum')
            ->postJson(self::createMerchantLocationEndpoint(), self::VALID_PAYLOAD);

        $response->assertStatus(Response::HTTP_UNAUTHORIZED);
    }
}
