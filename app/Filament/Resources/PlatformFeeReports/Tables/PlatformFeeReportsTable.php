<?php

declare(strict_types=1);

namespace App\Filament\Resources\PlatformFeeReports\Tables;

use App\Enums\PlatformFeeReportStatus;
use App\Filament\Actions\PlatformFeeReport\DownloadPlatformFeeReportAction;
use App\Filament\Actions\PlatformFeeReport\MarkPlatformFeeReportAsPaidAction;
use App\Support\Filament\Placeholder;
use Filament\Actions\BulkActionGroup;
use Filament\Actions\DeleteBulkAction;
use Filament\Actions\ForceDeleteBulkAction;
use Filament\Actions\RestoreBulkAction;
use Filament\Actions\ViewAction;
use Filament\Tables\Columns\TextColumn;
use Filament\Tables\Filters\SelectFilter;
use Filament\Tables\Filters\TrashedFilter;
use Filament\Tables\Table;

class PlatformFeeReportsTable
{
    public static function configure(Table $table): Table
    {
        return $table
            ->defaultSort('created_at', 'desc')
            ->columns([
                TextColumn::make('period_start')
                    ->label('Period Start')
                    ->date('d M Y')
                    ->sortable(),

                TextColumn::make('period_end')
                    ->label('Period End')
                    ->date('d M Y')
                    ->sortable(),

                TextColumn::make('total_gmv')
                    ->label('Total GMV')
                    ->prefix('RM ')
                    ->numeric(decimalPlaces: 2)
                    ->sortable(),

                TextColumn::make('total_platform_fees')
                    ->label('Total Platform Fees')
                    ->prefix('RM ')
                    ->numeric(decimalPlaces: 2)
                    ->sortable(),

                TextColumn::make('total_processing_costs')
                    ->label('Total Processing Costs')
                    ->prefix('RM ')
                    ->numeric(decimalPlaces: 2)
                    ->sortable(),

                TextColumn::make('status')
                    ->badge()
                    ->formatStateUsing(fn (PlatformFeeReportStatus $state) => $state->label())
                    ->color(fn (PlatformFeeReportStatus $state) => $state->color()),

                TextColumn::make('generatedBy.full_name')
                    ->label('Generated By'),

                TextColumn::make('paid_at')
                    ->label('Paid At')
                    ->dateTime('d M Y, H:i')
                    ->placeholder(Placeholder::EMPTY)
                    ->sortable(),

                TextColumn::make('created_at')
                    ->dateTime('d M Y, H:i')
                    ->sortable()
                    ->toggleable(isToggledHiddenByDefault: true),
            ])
            ->filters([
                SelectFilter::make('status')
                    ->options(PlatformFeeReportStatus::class),

                TrashedFilter::make(),
            ])
            ->recordActions([
                ViewAction::make(),
                DownloadPlatformFeeReportAction::make(),
                MarkPlatformFeeReportAsPaidAction::make(),
            ])
            ->toolbarActions([
                BulkActionGroup::make([
                    DeleteBulkAction::make(),
                    ForceDeleteBulkAction::make(),
                    RestoreBulkAction::make(),
                ]),
            ]);
    }
}
