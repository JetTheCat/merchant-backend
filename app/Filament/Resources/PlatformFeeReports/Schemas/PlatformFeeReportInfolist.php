<?php

declare(strict_types=1);

namespace App\Filament\Resources\PlatformFeeReports\Schemas;

use App\Enums\FeeReportStatus;
use App\Support\Filament\Placeholder;
use Filament\Infolists\Components\TextEntry;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;

class PlatformFeeReportInfolist
{
    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                Section::make('Report Details')
                    ->columns(2)
                    ->schema([
                        TextEntry::make('status')
                            ->badge()
                            ->formatStateUsing(fn (FeeReportStatus $state) => $state->label())
                            ->color(fn (FeeReportStatus $state) => $state->color()),

                        TextEntry::make('generatedBy.full_name')
                            ->label('Generated By'),

                        TextEntry::make('period_start')
                            ->label('Period Start')
                            ->date('d M Y'),

                        TextEntry::make('period_end')
                            ->label('Period End')
                            ->date('d M Y'),

                        TextEntry::make('created_at')
                            ->label('Generated At')
                            ->dateTime('d M Y, H:i'),
                    ]),

                Section::make('Financial Summary')
                    ->columns(2)
                    ->schema([
                        TextEntry::make('total_gmv')
                            ->label('Total GMV')
                            ->prefix('RM ')
                            ->numeric(decimalPlaces: 2),

                        TextEntry::make('total_platform_fees')
                            ->label('Total Platform Fees')
                            ->prefix('RM ')
                            ->numeric(decimalPlaces: 2),

                        TextEntry::make('total_processing_costs')
                            ->label('Total Processing Costs')
                            ->prefix('RM ')
                            ->numeric(decimalPlaces: 2),
                    ]),

                Section::make('Payment')
                    ->columns(2)
                    ->schema([
                        TextEntry::make('payment_reference')
                            ->label('Payment Reference')
                            ->placeholder(Placeholder::EMPTY),

                        TextEntry::make('paid_at')
                            ->label('Paid At')
                            ->dateTime('d M Y, H:i')
                            ->placeholder(Placeholder::EMPTY),
                    ]),
            ]);
    }
}
